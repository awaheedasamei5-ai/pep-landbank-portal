"use client";

import { useState } from "react";
import { Download, Vault as VaultIcon } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Card, CardContent } from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from "@/components/ui/table";
import { TableEmpty } from "@/components/table-empty";
import { Badge } from "@/components/ui/badge";
import { PageHeader } from "@/components/page-header";
import { useContractGenerations, useContractTemplates } from "../hooks/useContractTemplates";
import { requireSupabase } from "@/lib/supabase.client";

// NEW page (docs/plans/16-contract-of-sale-build-plan.md §4) -- a real
// browsing UI over contract_generations, the data that already existed
// but had no UI of its own (every "Generate" creates this row, but it
// only ever surfaced as a flat "Previously generated" list on the
// Generate screen itself). Re-download always serves the stored
// content_snapshot's PDF -- never regenerates -- matching the integrity
// rule the generation pipeline itself already enforces (§8 of the
// blueprint): a template edit after generation can never retroactively
// change what a past generation shows.
export function ContractVaultScreen() {
  const { data: generations, isLoading } = useContractGenerations();
  const { data: templates } = useContractTemplates();
  const [query, setQuery] = useState("");

  const q = query.trim().toLowerCase();
  const filtered = (generations ?? []).filter((g) => !q || g.clientName.toLowerCase().includes(q));

  return (
    <div>
      <PageHeader title="Contract vault" description="Every contract ever issued, with its real stored PDF." />

      <Card className="mb-4">
        <CardContent className="pt-6">
          <Input placeholder="Search by client name…" value={query} onChange={(e) => setQuery(e.target.value)} className="max-w-sm" />
        </CardContent>
      </Card>

      <Card>
        <CardContent className="pt-6">
          <Table>
            <TableHeader>
              <TableRow>
                <TableHead>Client</TableHead>
                <TableHead>Template</TableHead>
                <TableHead>Generated by</TableHead>
                <TableHead>Date</TableHead>
                <TableHead className="text-right">Document</TableHead>
              </TableRow>
            </TableHeader>
            <TableBody>
              {isLoading ? (
                <TableEmpty colSpan={5} message="Loading…" />
              ) : filtered.length === 0 ? (
                <TableEmpty colSpan={5} message={q ? "No contracts match that search." : "No contracts generated yet."} />
              ) : (
                filtered.map((g) => {
                  const templateName = g.templateId ? (templates ?? []).find((t) => t.id === g.templateId)?.name ?? "Template" : "Standard (legacy document)";
                  return (
                    <TableRow key={g.id}>
                      <TableCell className="font-medium">{g.clientName}</TableCell>
                      <TableCell>
                        {g.templateId ? (
                          <span>
                            {templateName}
                            {g.versionNumberSnapshot != null && <span className="ml-1 font-mono text-xs text-muted-foreground">v{g.versionNumberSnapshot}</span>}
                          </span>
                        ) : (
                          <Badge variant="outline">Legacy</Badge>
                        )}
                      </TableCell>
                      <TableCell>{g.generatedByName}</TableCell>
                      <TableCell>{g.generatedAt.slice(0, 10)}</TableCell>
                      <TableCell className="text-right">
                        <VaultDownloadButton storagePath={g.pdfStoragePath} />
                      </TableCell>
                    </TableRow>
                  );
                })
              )}
            </TableBody>
          </Table>
        </CardContent>
      </Card>
    </div>
  );
}

function VaultDownloadButton({ storagePath }: { storagePath: string | null }) {
  const [busy, setBusy] = useState(false);

  if (!storagePath) {
    return (
      <span className="inline-flex items-center gap-1 text-xs text-muted-foreground">
        <VaultIcon className="size-3.5" />
        No stored PDF
      </span>
    );
  }

  async function open() {
    setBusy(true);
    try {
      const { data, error } = await requireSupabase().storage.from("contract-pdfs").createSignedUrl(storagePath!, 60);
      if (error) throw error;
      if (data?.signedUrl) window.open(data.signedUrl, "_blank", "noopener,noreferrer");
    } finally {
      setBusy(false);
    }
  }

  return (
    <Button type="button" size="sm" variant="outline" disabled={busy} onClick={open}>
      <Download />
      {busy ? "Opening…" : "Download"}
    </Button>
  );
}
