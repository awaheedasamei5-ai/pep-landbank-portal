"use client";

import { useState } from "react";
import Link from "next/link";
import { Download, Pencil, Trash2, Vault as VaultIcon } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Card, CardContent } from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { Dialog, DialogContent, DialogDescription, DialogFooter, DialogHeader, DialogTitle } from "@/components/ui/dialog";
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from "@/components/ui/table";
import { TableEmpty } from "@/components/table-empty";
import { Badge } from "@/components/ui/badge";
import { PageHeader } from "@/components/page-header";
import { useAllContractsForVault, useContractTemplates, useRemoveContractFromActiveVault, useRemoveLegacyContractFromActiveVault } from "../hooks/useContractTemplates";
import { requireSupabase } from "@/lib/supabase.client";
import { useSessionStore } from "../../../auth/useSessionStore";
import type { ContractGeneration } from "../../../types/domain";

// NEW page (docs/plans/16-contract-of-sale-build-plan.md §4) -- a real
// browsing UI over contract_generations, the data that already existed
// but had no UI of its own (every "Generate" creates this row, but it
// only ever surfaced as a flat "Previously generated" list on the
// Generate screen itself). Re-download always serves the stored
// content_snapshot's PDF -- never regenerates -- matching the integrity
// rule the generation pipeline itself already enforces (§8 of the
// blueprint): a template edit after generation can never retroactively
// change what a past generation shows.
export function ContractVaultScreen() {
  const { data: generations, isLoading } = useAllContractsForVault();
  const { data: templates } = useContractTemplates();
  const [query, setQuery] = useState("");
  const [showRemoved, setShowRemoved] = useState(false);
  const [removeTarget, setRemoveTarget] = useState<ContractGeneration | null>(null);
  const [removeReason, setRemoveReason] = useState("");
  const manager = useSessionStore((state) => state.profile?.role === "manager");
  const removeFromVault = useRemoveContractFromActiveVault();
  const removeLegacy = useRemoveLegacyContractFromActiveVault();

  const q = query.trim().toLowerCase();
  const filtered = (generations ?? []).filter((g) => (showRemoved || !g.voidedAt) && (!q || g.clientName.toLowerCase().includes(q)));

  function closeRemove() {
    setRemoveTarget(null);
    setRemoveReason("");
    removeFromVault.reset();
    removeLegacy.reset();
  }

  return (
    <div>
      <PageHeader title="Contract vault" description="Download issued PDFs, correct KYC through a replacement contract, or remove an erroneous copy from the active list." />

      <Card className="mb-4">
        <CardContent className="pt-6">
          <div className="flex flex-wrap items-center gap-3">
            <Input placeholder="Search by client name…" value={query} onChange={(e) => setQuery(e.target.value)} className="max-w-sm" />
            {manager && <Button type="button" variant="outline" size="sm" onClick={() => setShowRemoved((value) => !value)}>{showRemoved ? "Hide removed" : "Show removed"}</Button>}
          </div>
        </CardContent>
      </Card>

      <Card>
        <CardContent className="pt-6">
          <Table>
            <TableHeader>
              <TableRow>
                <TableHead>Client</TableHead>
                <TableHead>Template</TableHead>
                <TableHead>Generated by</TableHead>
                <TableHead>Date</TableHead>
                <TableHead className="text-right">Document</TableHead>
                <TableHead className="text-right">Actions</TableHead>
              </TableRow>
            </TableHeader>
            <TableBody>
              {isLoading ? (
                <TableEmpty colSpan={6} message="Loading…" />
              ) : filtered.length === 0 ? (
                <TableEmpty colSpan={6} message={q ? "No contracts match that search." : "No contracts in this view."} />
              ) : (
                filtered.map((g) => {
                  const templateName = g.templateId ? (templates ?? []).find((t) => t.id === g.templateId)?.name ?? "Template" : "Standard (legacy document)";
                  return (
                    <TableRow key={g.id}>
                      <TableCell className="font-medium">
                        {g.clientName}
                        {/* docs/plans/17-contract-of-sale-v3-gaps-plan.md Phase 3 -- a
                            walk-in generation has no leadId at all (by design, never
                            written to Pipeline), flagged here so it's never mistaken
                            for a real pipeline lead later. */}
                        {g.leadId == null && (
                          <Badge variant="outline" className="ml-2">
                            Walk-in
                          </Badge>
                        )}
                        {g.voidedAt && <Badge variant="secondary" className="ml-2">Removed</Badge>}
                        {g.voidedAt && <p className="mt-1 text-xs text-muted-foreground">Removed {g.voidedAt.slice(0, 10)} · {g.voidReason}</p>}
                      </TableCell>
                      <TableCell>
                        {g.templateId ? (
                          <span>
                            {templateName}
                            {g.versionNumberSnapshot != null && <span className="ml-1 font-mono text-xs text-muted-foreground">v{g.versionNumberSnapshot}</span>}
                          </span>
                        ) : (
                          <Badge variant="outline">{g.pdfStoragePath ? "Standard PDF" : "Legacy record"}</Badge>
                        )}
                      </TableCell>
                      <TableCell>{g.generatedByName}</TableCell>
                      <TableCell>{g.generatedAt.slice(0, 10)}</TableCell>
                      <TableCell className="text-right">
                        <VaultDownloadButton storagePath={g.pdfStoragePath} />
                      </TableCell>
                      <TableCell className="text-right">
                        <div className="flex justify-end gap-1">
                          {!g.voidedAt && g.pdfStoragePath && <Button asChild type="button" size="sm" variant="outline"><Link href={g.leadId ? `/dashboard/contract-of-sale/generate?lead=${encodeURIComponent(g.leadId)}&correct=${encodeURIComponent(g.id)}` : `/dashboard/contract-of-sale/generate?copy=${encodeURIComponent(g.id)}`}><Pencil />Correct KYC</Link></Button>}
                          {manager && !g.voidedAt && <Button type="button" size="sm" variant="outline" onClick={() => setRemoveTarget(g)}><Trash2 />Remove</Button>}
                        </div>
                      </TableCell>
                    </TableRow>
                  );
                })
              )}
            </TableBody>
          </Table>
        </CardContent>
      </Card>

      <Dialog open={!!removeTarget} onOpenChange={(open) => { if (!open) closeRemove(); }}>
        <DialogContent>
          <DialogHeader>
            <DialogTitle>Remove from active vault?</DialogTitle>
            <DialogDescription>{removeTarget?.isLegacyRecord ? "This older record has no stored PDF. Its audit entry remains available under Show removed." : "The issued PDF is kept in the audit history. This copy will disappear from the active list, and Management can find it under Show removed."}</DialogDescription>
          </DialogHeader>
          <div className="space-y-2">
            <Label htmlFor="contract-remove-reason">Reason for removal</Label>
            <Input id="contract-remove-reason" value={removeReason} onChange={(event) => setRemoveReason(event.target.value)} placeholder="For example, incorrect client address" />
          </div>
          {(removeFromVault.isError || removeLegacy.isError) && <p role="alert" className="text-sm text-destructive">{((removeFromVault.error || removeLegacy.error) as Error).message}</p>}
          <DialogFooter>
            <Button type="button" variant="outline" onClick={closeRemove}>Cancel</Button>
            <Button type="button" variant="destructive" disabled={removeReason.trim().length < 5 || removeFromVault.isPending || removeLegacy.isPending} onClick={() => { if (!removeTarget) return; const action = removeTarget.isLegacyRecord ? removeLegacy : removeFromVault; action.mutate({ id: removeTarget.id, reason: removeReason }, { onSuccess: closeRemove }); }}>{removeFromVault.isPending || removeLegacy.isPending ? "Removing…" : "Remove from active vault"}</Button>
          </DialogFooter>
        </DialogContent>
      </Dialog>
    </div>
  );
}

function VaultDownloadButton({ storagePath }: { storagePath: string | null }) {
  const [busy, setBusy] = useState(false);

  if (!storagePath) {
    return (
      <span className="inline-flex items-center gap-1 text-xs text-muted-foreground">
        <VaultIcon className="size-3.5" />
        No stored PDF
      </span>
    );
  }

  async function open() {
    setBusy(true);
    try {
      const { data, error } = await requireSupabase().storage.from("contract-pdfs").createSignedUrl(storagePath!, 60);
      if (error) throw error;
      if (data?.signedUrl) window.open(data.signedUrl, "_blank", "noopener,noreferrer");
    } finally {
      setBusy(false);
    }
  }

  return (
    <Button type="button" size="sm" variant="outline" disabled={busy} onClick={open}>
      <Download />
      {busy ? "Opening…" : "Download"}
    </Button>
  );
}
