export async function buildSummaryReportPdf(
  range: DateRange,
  collected: number,
  expensesTotal: number,
  commissionTotal: number,
  payrollTotal: number,
  companyName: string,
  generatedBy: string | null | undefined,
  logoImage: string | null,
): Promise<jsPDF> {
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const pageW = doc.internal.pageSize.getWidth();
  const logo = await loadLogo(logoImage);
  let y = header(doc, "Financial Summary", range, companyName, generatedBy, logo);

  const net = collected - expensesTotal - commissionTotal - payrollTotal;
  y = pdfSectionTitle(doc, y, pageW, "Income statement");
  y = pdfSimpleTable(
    doc,
    y,
    pageW,
    ["LINE", "AMOUNT"],
    [
      ["Collected (revenue)", money(collected)],
      ["Expenses", `(${money(expensesTotal)})`],
      ["Commission paid", `(${money(commissionTotal)})`],
      ["Payroll paid", `(${money(payrollTotal)})`],
      ["Net", money(net)],
    ],
    [0.6, 0.4],
  );

  pdfReportFooter(doc, companyName);
  pdfGeneratedStamp(doc, generatedBy);
  return doc;
}
