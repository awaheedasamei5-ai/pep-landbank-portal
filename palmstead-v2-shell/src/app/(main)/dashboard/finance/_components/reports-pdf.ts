// Real income-statement-shaped Financial Summary, matching Xero's own
// real P&L grouping (Revenue, then each outflow its own section, then a
// final emphasized Net row) -- not a row of stat boxes. Every section
// carries its real line items, not just a number.
export async function buildSummaryReportPdf(
  range: DateRange,
  payments: PaymentsReportRow[],
  expenses: ExpensesReportRow[],
  commission: CommissionReportRow[],
  payroll: PayrollReportRow[],
  companyName: string,
  generatedBy: string | null | undefined,
  logoImage: string | null,
): Promise<jsPDF> {
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const pageW = doc.internal.pageSize.getWidth();
  const logo = await loadLogo(logoImage);
  let y = header(doc, "Financial Summary", range, companyName, generatedBy, logo);

  const approvedPayments = payments.filter((r) => r.status === "approved");
  const approvedExpenses = expenses.filter((r) => r.status === "approved");
  const collected = approvedPayments.reduce((s, r) => s + r.amount, 0);
  const expensesTotal = approvedExpenses.reduce((s, r) => s + r.amount, 0);
  const commissionTotal = commission.reduce((s, r) => s + r.total, 0);
  const payrollTotal = payroll.reduce((s, r) => s + r.net, 0);
  const net = collected - expensesTotal - commissionTotal - payrollTotal;

  y = pdfSectionTitle(doc, y, pageW, "Income statement");

  const revenueLines: PdfLedgerLine[] = approvedPayments.slice(0, 40).map((r) => ({ label: `${fmtDate(r.paymentDate)} — ${r.leadName}`, value: money(r.amount) }));
  if (approvedPayments.length > 40) revenueLines.push({ label: `…and ${approvedPayments.length - 40} more (see Payments report for full detail)`, value: "" });
  y = pdfLedgerSection(doc, y, pageW, "Revenue — collected payments", revenueLines, "Total revenue", money(collected));

  y = checkPageBreak(doc, y);
  const expenseByCategory = new Map<string, number>();
  for (const r of approvedExpenses) expenseByCategory.set(r.category, (expenseByCategory.get(r.category) ?? 0) + r.amount);
  const expenseLines: PdfLedgerLine[] = [...expenseByCategory.entries()].sort((a, b) => b[1] - a[1]).map(([c, a]) => ({ label: c, value: money(a) }));
  y = pdfLedgerSection(doc, y, pageW, "Expenses", expenseLines, "Total expenses", money(expensesTotal));

  y = checkPageBreak(doc, y);
  const commissionByAgent = new Map<string, number>();
  for (const r of commission) commissionByAgent.set(r.agentName, (commissionByAgent.get(r.agentName) ?? 0) + r.total);
  const commissionLines: PdfLedgerLine[] = [...commissionByAgent.entries()].sort((a, b) => b[1] - a[1]).map(([a, v]) => ({ label: a, value: money(v) }));
  y = pdfLedgerSection(doc, y, pageW, "Commission paid", commissionLines, "Total commission", money(commissionTotal));

  y = checkPageBreak(doc, y);
  const payrollByStaff = new Map<string, number>();
  for (const r of payroll) payrollByStaff.set(r.staffName, (payrollByStaff.get(r.staffName) ?? 0) + r.net);
  const payrollLines: PdfLedgerLine[] = [...payrollByStaff.entries()].sort((a, b) => b[1] - a[1]).map(([s, v]) => ({ label: s, value: money(v) }));
  y = pdfLedgerSection(doc, y, pageW, "Payroll paid", payrollLines, "Total payroll", money(payrollTotal));

  y = checkPageBreak(doc, y);
  y = pdfLedgerSection(doc, y, pageW, "Net", [], "Net (revenue − expenses − commission − payroll)", money(net), { emphasize: true });

  pdfReportFooter(doc, companyName);
  pdfGeneratedStamp(doc, generatedBy);
  return doc;
}
