import { jsPDF } from "jspdf";

import { loadImageAsDataUri } from "@/webnext/shared/lib/image";
import { pdfBrandedHeader, pdfGeneratedStamp, pdfLedgerSection, pdfReportFooter, pdfSectionTitle, type PdfLedgerLine } from "@/webnext/shared/lib/pdfReport";

import type { CommissionReportRow, DateRange, ExpensesReportRow, PaymentsReportRow, PayrollReportRow } from "./use-finance-reports";

// Real grouped-ledger report PDFs (Part B.10, rebuilt 2026-10-10 against
// Xero's own real published P&L sample -- see docs/plans/05-accounting-app-blueprint.md
// Part E.1). Every report here is a real statement-shaped document: a
// bold section header, every real row of detail (not collapsed into a
// handful of stat boxes), a shaded TOTAL row per section -- the same
// visual family pdfLedgerSection already gives every report in this app.
function money(n: number): string {
  return `GHS ${n.toLocaleString("en-GH", { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
}

function fmtDate(d: string): string {
  return new Date(`${d}T00:00:00`).toLocaleDateString("en-GB");
}

async function loadLogo(uploaded: string | null): Promise<string | null> {
  if (uploaded) return uploaded;
  try {
    return await loadImageAsDataUri("/trulander-logo.png");
  } catch {
    return null;
  }
}

function header(doc: jsPDF, title: string, range: DateRange, companyName: string, generatedBy: string | null | undefined, logo: string | null): number {
  let y = pdfBrandedHeader(doc, title.toUpperCase(), `${fmtDate(range.start)} – ${fmtDate(range.end)}`, [companyName, `Generated by ${generatedBy ?? "Management"}`], logo);
  return y + 6;
}

function checkPageBreak(doc: jsPDF, y: number): number {
  if (y > 262) {
    doc.addPage();
    return 16;
  }
  return y;
}

export async function buildPaymentsReportPdf(range: DateRange, rows: PaymentsReportRow[], companyName: string, generatedBy: string | null | undefined, logoImage: string | null): Promise<jsPDF> {
  const doc = new jsPDF({ unit: "mm", format: "a4" });
  const pageW = doc.internal.pageSize.getWidth();
  const logo = await loadLogo(logoImage);
  let y = header(doc, "Payments Report", range, companyName, generatedBy, logo);

  const approved = rows.filter((r) => r.status === "approved");
  const total = approved.reduce((s, r) => s + r.amount, 0);

  // Grouped by agent, matching a real receivables-by-salesperson breakdown
  // -- not a flat undifferentiated list.
  const byAgent = new Map<string, PaymentsReportRow[]>();
  for (const r of rows) {
    const list = byAgent.get(r.agentKey) ?? [];
    list.push(r);
    byAgent.set(r.agentKey, list);
  }

  y = pdfSectionTitle(doc, y, pageW, "Payments", `${rows.length} transaction(s), ${approved.length} approved`);
  for (const [agentKey, agentRows] of [...byAgent.entries()].sort((a, b) => b[1].length - a[1].length)) {
    y = checkPageBreak(doc, y);
    const agentApproved = agentRows.filter((r) => r.status === "approved");
    const lines: PdfLedgerLine[] = agentRows.map((r) => ({
      label: `${fmtDate(r.paymentDate)} — ${r.leadName} (${r.paymentMethod ?? "—"}, ${r.status})`,
      value: money(r.amount),
    }));
    y = pdfLedgerSection(doc, y, pageW, agentKey, lines, `Total — ${agentKey}`, money(agentApproved.reduce((s, r) => s + r.amount, 0)));
  }

  y = checkPageBreak(doc, y);
  y = pdfLedgerSection(doc, y, pageW, "Overall", [], "Total collected (approved)", money(total), { emphasize: true });

  pdfReportFooter(doc, companyName);
  pdfGeneratedStamp(doc, generatedBy);
  return doc;
}

